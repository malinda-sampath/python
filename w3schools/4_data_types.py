# str data type
a = "Hello, World!"
a = str("Hello, World!")

# int data types
b = 20
b = int(20)

# float data type
c = 20.5
c = float(20.5)

# complex data type
d = 1j
d = complex(1, 1)

# list data type
e = ["apple", "banana", "cherry"]
e = list(("apple", "banana", "cherry"))

# tuple data type
f = ("apple", "banana", "cherry")
f = tuple(("apple", "banana", "cherry"))

# range data type
g = range(6)
g = range(6)

# dict data type
h = {"name" : "John", "age" : 36}
h = dict(name="John", age=36)

# set data type
i = {"apple", "banana", "cherry"}
i = set(("apple", "banana", "cherry"))

# frozenset data type
j = frozenset({"apple", "banana", "cherry"})
j = frozenset(("apple", "banana", "cherry"))

# bool data type
k = True
k = bool(1)

# bytes data type
l = b"Hello"
l = bytes(5)

# bytearray data type
m = bytearray(5)
m = bytearray(5)


# memoryview data type
n = memoryview(bytes(5))
n = memoryview(bytes(5))

# None data type
n = None

